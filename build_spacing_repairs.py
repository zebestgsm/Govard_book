"""Generate guarded, OCR-supported spacing repairs from review suggestions.

Only splits whose every part is a known word are emitted. The result is a
 draft improvement, not a claim of full transcription verification.
"""
import json, re
from pathlib import Path
import reader, reference_sources

ROOT = Path(__file__).resolve().parent

def words(text):
    return re.findall(r"[a-z]+(?:['’-][a-z]+)*", text.lower().replace('ſ', 's'))

vocab = set()
for _, text, _, _ in reference_sources.sources():
    vocab.update(words(text))
for path in (ROOT / 'ocr_review').glob('*_*.txt'):
    vocab.update(words(path.read_text(encoding='utf-8')))
vocab.update('''a i an the of to in and or but for with without by from at on into upon is are was were be been being have has had do does did not no nor so as if it its this that these those there their they them he she his her we our us you your who whom which what when where why how all any some many few more most less least very much may might can could shall should will would must one two three four five six seven eight nine ten first second third last next other another such same only also even ever never always often sometimes here now then than because before after while during between among through over under above below up down out off again further farther thus therefore however moreover nevertheless viz etc ed pp page pages vol vols mr mrs dr sir john howard gaol gaols jail jails prison prisons prisoner prisoners gaoler gaolers bridewell bridewells felons felony debtors debtor keeper keepers county counties circuit circuits assize assizes sessions session london middlesex westminster england english britain british ireland irish scotland scotch wales foreign europe france french holland dutch germany german italy italian spain spanish portugal portuguese switzerland swiss sweden swedish denmark danish russia russian prussia prussian austria austrian turkey turkish venice venetian amsterdam rotterdam utrecht groningen leiden delft hague haarlem dort leyden bern zurich basil geneva paris brest morlaix dinan dinnan carhaix lisbon hanover newgate fleet marshalsea kingston salisbury exeter durham hull norwich bedford cambridge oxford worcester gloucester bristol liverpool chester york newcastle lancaster plymouth portsmouth gosport thames towcester northampton warwick birmingham manchester'''.split())

suggestions = json.loads((ROOT / 'ocr_review/suggestions.json').read_text(encoding='utf-8'))
repairs = {}
skipped = []
saved = reader.inline_editor.load_edits()
for number in range(1, len(reader.PAGES) + 1):
    token = reader._current_corrections.set(())
    try:
        _, segments = reader.segment_state(number, edits={'spreads': {}})
    finally:
        reader._current_corrections.reset(token)
    user = saved['spreads'].get(str(number), {}).get('segments', {})
    by_segment = {}
    for item in suggestions.get(str(number), []):
        sid, old, new = item['segment'], item['old'], item['new']
        if sid in user or sid not in segments:
            skipped.append((number, sid, 'user-or-missing')); continue
        text = segments[sid]
        if text.count(old) != 1 or old == new or ' ' in old:
            skipped.append((number, sid, 'ambiguous')); continue
        parts = new.split()
        if not all(p.lower().strip(".,;:!?()[]'’\"-") in vocab or re.fullmatch(r'[ivxlcdm]+|[A-Z]\.', p) for p in parts):
            skipped.append((number, sid, 'unknown-word')); continue
        by_segment.setdefault(sid, []).append((old, new))
    if by_segment:
        repairs[number] = {sid: (segments[sid][:48], pairs) for sid, pairs in by_segment.items()}

lines = ['"""Guarded spacing repairs supported by the alternate OCR.\n\nGenerated by build_spacing_repairs.py. These are draft improvements; the\nspreads remain marked for OCR review unless separately verified.\n"""\n', 'SPACING_REPAIRS = {']
for number, segs in sorted(repairs.items()):
    lines.append(f'    {number}: {{')
    for sid, (prefix, pairs) in sorted(segs.items(), key=lambda x: int(x[0][1:])):
        lines.append(f'        {sid!r}: ({prefix!r}, {pairs!r}),')
    lines.append('    },')
lines.append('}\n')
(ROOT / 'spacing_repairs.py').write_text('\n'.join(lines), encoding='utf-8')
print('Spreads with spacing repairs:', len(repairs))
print('Segments:', sum(len(v) for v in repairs.values()))
print('Splits:', sum(len(p) for v in repairs.values() for _, p in v.values()))
print('Skipped:', len(skipped))
