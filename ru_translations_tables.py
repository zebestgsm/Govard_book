def _row_label(cell):
    if cell in _ROW_LABELS:
        return _ROW_LABELS[cell]
    if cell.endswith(' Bridewell'):
        return cell[:-9] + ', испр. дом'
    if cell.endswith(" Sheriff's Ward"):
        return cell[:-14] + ', отделение шерифа'
    if cell == 'Ripon Liberty':
        return 'Ripon, вольность'
    if cell == "St. Alban's Borough Gaol":
        return "St. Alban's, городская тюрьма"
    if cell == 'Tothill-Fields Bridewell':
        return 'Тотхилл-Филдс, испр. дом'
    if cell == "St. George's Fields Bridewell":
        return 'Сент-Джорджс-Филдс, испр. дом'
    return cell


def _translate_rows(table):
    rows = []
    for line in table.splitlines():
        if not line:
            continue
        cells = line.split('\t')
        cells[0] = _row_label(cells[0])
        rows.append('\t'.join(cells))
    return '\n'.join(rows)


def tr(table):
    # H_RU already ends in a newline: never join it to the first data row.
    return H_RU + _translate_rows(table.split('\n', 1)[1])

